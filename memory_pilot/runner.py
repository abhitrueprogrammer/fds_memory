"""Runner for executing sequence conditions on SWE-bench Verified Mini."""

import json
import os
from pathlib import Path
import shutil
import subprocess
import time
from typing import Any
from datasets import load_dataset
from dotenv import load_dotenv
import unidiff

load_dotenv()

from minisweagent.config import builtin_config_dir, get_config_from_spec
from minisweagent.run.benchmarks.swebench import process_instance
from minisweagent.run.benchmarks.utils.batch_progress import RunBatchProgressManager
from minisweagent.utils.serialize import recursive_merge

from memory_pilot.condition_a import ConditionAMemory
from memory_pilot.condition_b import ConditionBMemory
from memory_pilot.condition_c import ConditionCMemory
from memory_pilot.condition_d import ConditionDMemory
from memory_pilot.interface import BaseMemory

DEFAULT_CONFIG_FILE = Path(__file__).resolve().parent.parent / "swebench.yaml"


def get_memory_for_condition(condition: str) -> BaseMemory:
    cond = condition.upper()
    if cond == "A":
        return ConditionAMemory(token_budget=1200)
    elif cond == "B":
        return ConditionBMemory(token_budget=1200, top_k=5)
    elif cond == "C":
        return ConditionCMemory(token_budget=1200)
    elif cond == "D":
        return ConditionDMemory(token_budget=1200, top_files_k=5)
    else:
        raise ValueError(f"Unknown condition: {condition}")


def extract_files_from_patch(patch_str: str) -> list[str]:
    if not patch_str or not patch_str.strip():
        return []
    try:
        patch_set = unidiff.PatchSet(patch_str)
        files = []
        for p in patch_set:
            path = p.path
            if path.startswith("a/") or path.startswith("b/"):
                path = path[2:]
            files.append(path)
        return files
    except Exception:
        return []


def run_condition_sequence(
    condition: str,
    sequence: list[str],
    repo_dir: Path,
    output_dir: Path,
    model_name: str = "gemini/gemini-3.5-flash-lite",
    step_limit: int = 50,
) -> list[dict[str, Any]]:


    """Run an entire condition sequence with strict sequential memory updates."""
    memory = get_memory_for_condition(condition)
    memory.reset()

    ds = load_dataset("MariusHobbhahn/swe-bench-verified-mini", split="test")
    tasks_by_id = {x["instance_id"]: x for x in ds}

    cond_dir = output_dir / f"condition_{condition.upper()}"
    cond_dir.mkdir(parents=True, exist_ok=True)

    task_results = []

    # Prepare mini-swe-agent config
    configs = [get_config_from_spec(str(DEFAULT_CONFIG_FILE))]
    configs.append({
        "agent": {"step_limit": step_limit},
        "model": {
            "model_name": model_name,
            "cost_tracking": "ignore_errors",
            "model_kwargs": {"temperature": 0.0},
        },

    })
    base_config = recursive_merge(*configs)

    for pos, instance_id in enumerate(sequence):
        print(f"\n=======================================================", flush=True)
        print(f"[{condition.upper()}] Running Task {pos + 1}/{len(sequence)}: {instance_id}", flush=True)
        print(f"=======================================================", flush=True)

        task = tasks_by_id[instance_id]
        task_out_dir = cond_dir / instance_id
        task_out_dir.mkdir(parents=True, exist_ok=True)

        start_time = time.time()

        # 1. Get memory context for this task
        mem_output = memory.get_memory_context(task, repo_dir)
        print(f"Retrieved files ({len(mem_output.retrieved_files)}): {mem_output.retrieved_files}", flush=True)

        # Construct injected task prompt
        if mem_output.context_str:
            injected_prompt = (
                f"<repository_context>\n{mem_output.context_str}\n</repository_context>\n\n"
                f"{task['problem_statement']}"
            )
        else:
            injected_prompt = task["problem_statement"]

        # Prepare instance dict for mini-swe-agent with injected prompt
        instance_dict = dict(task)
        instance_dict["problem_statement"] = injected_prompt

        prompt_path = task_out_dir / "injected_task.txt"
        prompt_path.write_text(injected_prompt)

        # Run mini-swe-agent using official process_instance
        print(f"Launching mini-swe-agent...", flush=True)
        progress_manager = RunBatchProgressManager(
            1, task_out_dir / f"exit_statuses_{time.time()}.yaml"
        )
        process_instance(
            instance=instance_dict,
            output_dir=task_out_dir,
            config=base_config,
            progress_manager=progress_manager,
        )

        # Read predictions generated by agent
        preds_file = task_out_dir / "preds.json"
        model_patch = ""
        if preds_file.exists():
            try:
                preds_data = json.loads(preds_file.read_text())
                model_patch = preds_data.get(instance_id, {}).get("model_patch", "")
            except Exception as e:
                print(f"Error reading preds.json: {e}", flush=True)

        files_edited = extract_files_from_patch(model_patch)
        print(f"Agent finished. Files edited: {files_edited}", flush=True)

        # Read trajectory stats
        traj_file = task_out_dir / instance_id / f"{instance_id}.traj.json"
        api_calls = 0
        instance_cost = 0.0
        exit_status = "Unknown"
        if traj_file.exists():
            try:
                traj_data = json.loads(traj_file.read_text())
                info = traj_data.get("info", {})
                exit_status = info.get("exit_status", "Unknown")
                model_stats = info.get("model_stats", {})
                api_calls = model_stats.get("api_calls", 0)
                instance_cost = model_stats.get("instance_cost", 0.0)
            except Exception as e:
                print(f"Error reading trajectory: {e}", flush=True)

        # 2. Run SWE-bench evaluation harness
        print(f"Running SWE-bench harness evaluation on generated patch...", flush=True)
        harness_run_id = f"eval_{condition.lower()}_{instance_id}"
        harness_cmd = [
            ".venv/bin/python",
            "-m",
            "swebench.harness.run_evaluation",
            "--dataset_name",
            "MariusHobbhahn/swe-bench-verified-mini",
            "--split",
            "test",
            "--instance_ids",
            instance_id,
            "--predictions_path",
            str(preds_file) if preds_file.exists() else "smoke_test_run/preds.json",
            "--max_workers",
            "1",
            "--run_id",
            harness_run_id,
            "--report_dir",
            str(task_out_dir),
        ]
        env = os.environ.copy()
        harness_proc = subprocess.run(harness_cmd, env=env, text=True, capture_output=True)
        (task_out_dir / "harness_stdout.log").write_text(harness_proc.stdout)
        (task_out_dir / "harness_stderr.log").write_text(harness_proc.stderr)

        # Determine if task resolved
        resolved = False
        report_candidates = list(task_out_dir.glob(f"*{harness_run_id}*.json")) + list(
            Path(".").glob(f"*{harness_run_id}*.json")
        )
        for rep in report_candidates:
            try:
                rep_data = json.loads(rep.read_text())
                resolved_list = rep_data.get("resolved_instances", [])
                if instance_id in resolved_list:
                    resolved = True
                    break
            except Exception:
                pass

        if not resolved and "Instances resolved: 1" in harness_proc.stdout:
            resolved = True

        # Ensure all evaluation reports are placed in results/eval_reports/ and task_out_dir,
        # cleaning up the root directory to prevent clutter
        eval_reports_dir = Path("results/eval_reports")
        eval_reports_dir.mkdir(parents=True, exist_ok=True)
        for rep in Path(".").glob(f"*{harness_run_id}*.json"):
            shutil.copy2(rep, eval_reports_dir / rep.name)
            shutil.copy2(rep, task_out_dir / rep.name)
            rep.unlink(missing_ok=True)

        elapsed = time.time() - start_time
        print(f"Harness evaluation complete: resolved={resolved} in {elapsed:.1f}s", flush=True)

        # 3. Update memory after harness scores the task (Strict rule: NO leakage of gold patches)
        memory.update_memory(
            task=task,
            repo_dir=repo_dir,
            harness_passed=resolved,
            files_edited=files_edited,
            files_retrieved=mem_output.retrieved_files,
        )

        task_record = {
            "condition": condition.upper(),
            "instance_id": instance_id,
            "position": pos + 1,
            "resolved": resolved,
            "files_retrieved": mem_output.retrieved_files,
            "files_edited": files_edited,
            "api_calls": api_calls,
            "cost": instance_cost,
            "latency_seconds": round(elapsed, 2),
            "exit_status": exit_status,
            "memory_items_included": mem_output.metadata.get("items_included", []),
            "metadata": mem_output.metadata,
        }
        task_results.append(task_record)

        # Save record
        record_file = task_out_dir / "result_record.json"
        record_file.write_text(json.dumps(task_record, indent=2))

    summary_file = cond_dir / "summary.json"
    summary_file.write_text(json.dumps(task_results, indent=2))
    return task_results


